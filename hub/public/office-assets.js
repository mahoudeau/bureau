  // ---- rasterizer ---------------------------------------------------------
  // sprite(name, paletteKey) -> cached offscreen canvas. The cache is keyed
  // per palette, so a palette switch is a lazy full re-rasterize.
  var cache = {};
  function sprite(name, pal) {
    var key = pal + '/' + name;
    if (cache[key]) return cache[key];
    var grid = S[name];
    if (!grid) return null;
    var h = grid.length, w = grid[0].length;
    var cnv = document.createElement('canvas');
    cnv.width = w; cnv.height = h;
    var c = cnv.getContext('2d');
    var shades = PALETTES[pal].shades;
    for (var y = 0; y < h; y++) {
      for (var x = 0; x < w; x++) {
        var ch = grid[y][x];
        if (ch === '.' || ch === undefined) continue;
        c.fillStyle = shades[+ch];
        c.fillRect(x, y, 1, 1);
      }
    }
    cache[key] = cnv;
    return cnv;
  }
  function clearCache() { cache = {}; }

  // Mirror helper for side-facing sprites (draw with ctx.scale(-1,1)).
  function drawSprite(ctx, name, pal, x, y, mirror) {
    var cnv = sprite(name, pal);
    if (!cnv) return;
    x |= 0; y |= 0;
    if (mirror) {
      ctx.save();
      ctx.translate(x + cnv.width, y);
      ctx.scale(-1, 1);
      ctx.drawImage(cnv, 0, 0);
      ctx.restore();
    } else {
      ctx.drawImage(cnv, x, y);
    }
  }

  // Tile a named 8x8 sprite over a rect.
  function tileRect(ctx, name, pal, x, y, w, h) {
    var cnv = sprite(name, pal);
    if (!cnv) return;
    for (var ty = y; ty < y + h; ty += cnv.height)
      for (var tx = x; tx < x + w; tx += cnv.width)
        ctx.drawImage(cnv, tx, ty);
  }

  // ---- dither fills (the boss's brief: checkerboard + line) ---------------
  function dither50(ctx, pal, x, y, w, h, a, b) {
    var sh = PALETTES[pal].shades;
    for (var yy = 0; yy < h; yy++)
      for (var xx = 0; xx < w; xx++) {
        ctx.fillStyle = sh[((xx + yy) % 2) ? a : b];
        ctx.fillRect(x + xx, y + yy, 1, 1);
      }
  }
  function ditherLines(ctx, pal, x, y, w, h, a, b, vertical) {
    var sh = PALETTES[pal].shades;
    for (var yy = 0; yy < h; yy++)
      for (var xx = 0; xx < w; xx++) {
        var on = vertical ? (xx % 2) : (yy % 2);
        ctx.fillStyle = sh[on ? a : b];
        ctx.fillRect(x + xx, y + yy, 1, 1);
      }
  }

  // ---- bitmap text --------------------------------------------------------
  // drawText(ctx, 'HELLO', pal, x, y, shadeIndex). Uppercases; unknown
  // glyphs render as space. Returns the advance width.
  function drawText(ctx, str, pal, x, y, shade) {
    var sh = PALETTES[pal].shades[shade === undefined ? 0 : shade];
    ctx.fillStyle = sh;
    var cx = x | 0;
    str = String(str).toUpperCase();
    for (var i = 0; i < str.length; i++) {
      var g = FONT[str[i]] || FONT[' '];
      for (var gy = 0; gy < 5; gy++)
        for (var gx = 0; gx < 3; gx++)
          if (g[gy][gx] === '1') ctx.fillRect(cx + gx, (y | 0) + gy, 1, 1);
      cx += 4;
    }
    return cx - x;
  }
  function textWidth(str) { return String(str).length * 4; }

  // ---- TTF pixel text (Press Start, vendored at /office/font.ttf) ---------
  // fillText anti-aliases, which would break the 4-shade law on readback —
  // so the glyph run is drawn to an offscreen canvas and THRESHOLDED:
  // alpha >= 128 becomes the requested shade, everything else transparent.
  // Cached per (text, size); palette/shade resolve at blit time via a
  // second tiny recolor pass kept in the same cache entry per palette.
  var ttfCache = {};
  function ttfText(ctx, str, pal, x, y, shade, size) {
    size = size || 8;
    str = String(str);
    var key = pal + '/' + (shade === undefined ? 0 : shade) + '/' + size + '/' + str;
    var cnv = ttfCache[key];
    if (!cnv) {
      var w = Math.max(1, Math.ceil(str.length * size * 1.05) + 2), h = size + 4;
      var off = document.createElement('canvas');
      off.width = w; off.height = h;
      var c = off.getContext('2d');
      c.font = size + 'px OfficePixel, monospace';
      c.textBaseline = 'top';
      c.fillStyle = '#000';
      c.fillText(str, 0, 0);
      var img = c.getImageData(0, 0, w, h), d = img.data;
      var sh = PALETTES[pal].shades[shade === undefined ? 0 : shade];
      var r = parseInt(sh.slice(1, 3), 16), g = parseInt(sh.slice(3, 5), 16), b = parseInt(sh.slice(5, 7), 16);
      for (var i = 0; i < d.length; i += 4) {
        if (d[i + 3] >= 128) { d[i] = r; d[i + 1] = g; d[i + 2] = b; d[i + 3] = 255; }
        else d[i + 3] = 0;
      }
      c.putImageData(img, 0, 0);
      cnv = ttfCache[key] = off;
    }
    ctx.drawImage(cnv, x | 0, y | 0);
    return cnv.width;
  }
  function clearTtfCache() { ttfCache = {}; }

