#!/usr/bin/env node
// hub/tools/wordmark.js: draws the Bureau wordmark and its favicon in one bit,
// from the office's own 3x5 pixel font, the way getbureau.dev's title screen
// draws its logo: the word scaled 4x, a 1px outline, and the side extruded six
// cells down and leaning right. Here the face is solid ink, the outline paper
// and the side a 50% checker, the raised sheet's lift. No shine, no motion.
//
//   node hub/tools/wordmark.js
//
// Writes hub/public/app/wordmark.js (the app), hub/lib/wordmark.js (the link
// pages), hub/public/app/mark.svg (the favicon, a B) and favicon-16.png and
// favicon-32.png beside it. Each logo cell is one
// CSS pixel, so the checker stays crisp: draw it at its own width and height.
'use strict';
const fs = require('fs');
const path = require('path');
const vm = require('vm');

const HUB = path.join(__dirname, '..');

// The office's font, loaded as the office loads it. drawText only fills cells.
function glyphCells(text) {
  const sandbox = { window: {} };
  vm.runInNewContext(fs.readFileSync(path.join(HUB, 'public', 'office-assets.js'), 'utf8'), sandbox);
  const A = sandbox.window.OfficeAssets;
  const cells = new Set();
  const ctx = { set fillStyle(v) {}, fillRect(x, y) { cells.add(`${x},${y}`); } };
  A.drawText(ctx, text, Object.keys(A.PALETTES)[0], 0, 0, 0);
  return { cells, width: A.textWidth(text) - 1 };
}

// k: scale, depth: extrusion, sway: lean, as drawTitle and og-image.js do.
function build(text, k, depth, sway) {
  const { cells, width } = glyphCells(text);
  const face = new Set();
  for (const c of cells) {
    const [x, y] = c.split(',').map(Number);
    for (let i = 0; i < k; i += 1) for (let j = 0; j < k; j += 1) face.add(`${x * k + i + 1},${y * k + j + 1}`);
  }
  const shift = (set, dx, dy) => new Set([...set].map((c) => { const [x, y] = c.split(',').map(Number); return `${x + dx},${y + dy}`; }));
  const outline = new Set();
  for (const [dx, dy] of [[-1, 0], [1, 0], [0, -1], [0, 1]]) for (const c of shift(face, dx, dy)) if (!face.has(c)) outline.add(c);
  const side = new Set();
  for (let d = 1; d <= depth; d += 1) for (const c of shift(face, Math.round(sway * d / 3), d)) if (!face.has(c) && !outline.has(c)) side.add(c);
  const w = width * k + 2 + Math.round(sway * depth / 3);
  const h = 5 * k + depth + 2;
  return { face, outline, side, w, h };
}

// Cells to one path of horizontal runs.
function path_(cells) {
  const rows = new Map();
  for (const c of cells) {
    const [x, y] = c.split(',').map(Number);
    if (!rows.has(y)) rows.set(y, []);
    rows.get(y).push(x);
  }
  let d = '';
  for (const y of [...rows.keys()].sort((a, b) => a - b)) {
    const xs = rows.get(y).sort((a, b) => a - b);
    let start = xs[0];
    let prev = xs[0];
    for (const x of [...xs.slice(1), Infinity]) {
      if (x === prev + 1) { prev = x; continue; }
      d += `M${start} ${y}h${prev - start + 1}v1h${-(prev - start + 1)}z`;
      start = x;
      prev = x;
    }
  }
  return d;
}

// Ink: the face and every other cell of the side. Paper: the outline, which
// cuts the face from its side, and the side's other cells. A paper face only
// read as an outline on a paper bar; a solid face reads at 28px.
function layers(m, ditherSide) {
  const ink = new Set(m.face);
  const paper = new Set(m.outline);
  for (const c of m.side) {
    const [x, y] = c.split(',').map(Number);
    if (!ditherSide || (x + y) % 2 === 0) ink.add(c); else paper.add(c);
  }
  return { paper: path_(paper), ink: path_(ink) };
}

const word = build('BUREAU', 4, 6, 1);
const wl = layers(word, true);
const HEAD = '// Generated by hub/tools/wordmark.js from the office font. Change that, not this.\n';

// The app: built with the DOM, themed by classes, one CSS pixel per cell.
fs.writeFileSync(path.join(HUB, 'public', 'app', 'wordmark.js'), `${HEAD}
import { s } from './dom.js';

export const WORDMARK = { width: ${word.w}, height: ${word.h} };

export function wordmark(label = 'Bureau') {
  return s('svg', { class: 'app-wordmark', viewBox: '0 0 ${word.w} ${word.h}', width: ${word.w}, height: ${word.h}, 'shape-rendering': 'crispEdges', role: 'img', 'aria-label': label },
    s('path', { class: 'app-wordmark-paper', d: '${wl.paper}' }),
    s('path', { class: 'app-wordmark-ink', d: '${wl.ink}' }));
}
`);

// The link pages: the same drawing as markup.
fs.writeFileSync(path.join(HUB, 'lib', 'wordmark.js'), `${HEAD}'use strict';

module.exports = '<svg class="app-wordmark" viewBox="0 0 ${word.w} ${word.h}" width="${word.w}" height="${word.h}" shape-rendering="crispEdges" role="img" aria-label="Bureau"><path class="app-wordmark-paper" d="${wl.paper}"/><path class="app-wordmark-ink" d="${wl.ink}"/></svg>';
`);

// The favicon: the wordmark's own B, same scale, same dithered side. A Retina
// tab draws 16px with 32 device pixels, about one per cell, so the checker
// stays a checker. Centred in a square, so a tab doesn't squash it. Fixed
// colours: a file has no theme. The paper cells keep it visible on a dark tab bar.
const b = build('B', 4, 6, 1);
const bl = layers(b, true);
const side = Math.max(b.w, b.h) + 2;
const x0 = -Math.round((side - b.w) / 2);
const y0 = -Math.round((side - b.h) / 2);
fs.writeFileSync(path.join(HUB, 'public', 'app', 'mark.svg'),
  `<svg xmlns="http://www.w3.org/2000/svg" viewBox="${x0} ${y0} ${side} ${side}" shape-rendering="crispEdges"><path fill="#ffffff" d="${bl.paper}"/><path fill="#0b0d12" d="${bl.ink}"/></svg>\n`);

// PNG favicons, cell for cell, for the browsers that ignore an SVG one
// (Safari's tabs). 32px is the B above at one pixel per cell; 16px is the B
// at half scale, since the full one can't fit 16px without blurring.
const zlib = require('zlib');
const CRC = new Int32Array(256).map((_, n) => { let c = n; for (let k = 0; k < 8; k += 1) c = c & 1 ? 0xedb88320 ^ (c >>> 1) : c >>> 1; return c; });
const crc32 = (buf) => { let c = -1; for (const x of buf) c = CRC[(c ^ x) & 0xff] ^ (c >>> 8); return (c ^ -1) >>> 0; };
function chunk(type, data) {
  const len = Buffer.alloc(4); len.writeUInt32BE(data.length);
  const td = Buffer.concat([Buffer.from(type), data]);
  const crc = Buffer.alloc(4); crc.writeUInt32BE(crc32(td));
  return Buffer.concat([len, td, crc]);
}
function png(m, size) {
  const ink = new Set(); const paper = new Set();
  for (const c of m.face) ink.add(c);
  for (const c of m.outline) paper.add(c);
  for (const c of m.side) { const [x, y] = c.split(',').map(Number); ((x + y) % 2 === 0 ? ink : paper).add(c); }
  const ox = Math.floor((size - m.w) / 2); const oy = Math.floor((size - m.h) / 2);
  const rows = [];
  for (let y = 0; y < size; y += 1) {
    const row = Buffer.alloc(1 + size * 4);
    for (let x = 0; x < size; x += 1) {
      const key = `${x - ox},${y - oy}`;
      const rgba = ink.has(key) ? [11, 13, 18, 255] : paper.has(key) ? [255, 255, 255, 255] : [0, 0, 0, 0];
      row.set(rgba, 1 + x * 4);
    }
    rows.push(row);
  }
  const head = Buffer.alloc(13); head.writeUInt32BE(size, 0); head.writeUInt32BE(size, 4); head[8] = 8; head[9] = 6;
  return Buffer.concat([Buffer.from([137, 80, 78, 71, 13, 10, 26, 10]), chunk('IHDR', head), chunk('IDAT', zlib.deflateSync(Buffer.concat(rows))), chunk('IEND', Buffer.alloc(0))]);
}
fs.writeFileSync(path.join(HUB, 'public', 'app', 'favicon-32.png'), png(b, 32));
fs.writeFileSync(path.join(HUB, 'public', 'app', 'favicon-16.png'), png(build('B', 2, 3, 1), 16));

console.log(`wordmark ${word.w}x${word.h}, favicon B ${b.w}x${b.h}, PNG favicons 16 and 32`);
